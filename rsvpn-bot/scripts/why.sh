#!/usr/bin/env bash
#
# Одна команда на вопрос «почему бот не работает».
#
#     ./scripts/why.sh
#
# Собирает всё, что отвечает на этот вопрос, в одном выводе и в том
# порядке, в каком его читают: жив ли процесс → что он сказал перед
# смертью → что говорит Telegram → в порядке ли окружение → не кончилось
# ли место.
#
# Зачем скриптом: в четыре утра, с телефона, по ssh, человек не вспомнит
# ни путь к логам, ни имя процесса, ни как называется проверка. А вывод
# одной команды можно целиком отправить в чат и разобрать вместе.
#
# Ничего не чинит и не перезапускает нарочно: сначала узнать причину,
# потом решать. Перезапуск затирает половину улик.

set -uo pipefail
cd "$(dirname "$0")/.." || exit 1

PYTHON=".venv/bin/python"
[ -x "$PYTHON" ] || PYTHON="python3"

echo "════════════════════════════════════════════════════════════"
echo " 1. Процессы"
echo "════════════════════════════════════════════════════════════"
if command -v pm2 > /dev/null 2>&1; then
    pm2 list 2>/dev/null | grep -E 'rsvpn|name|status' || pm2 list
    echo
    # Счётчик перезапусков — главное число на этом экране: растёт
    # быстро = процесс падает сразу после старта, и причина в логе ошибок.
    pm2 describe rsvpn-bot 2>/dev/null | grep -E 'status|uptime|restarts|script args' || \
        echo "❌ процесса rsvpn-bot нет — pm2 start ecosystem.config.js"
else
    echo "❌ pm2 не найден"
fi

echo
echo "════════════════════════════════════════════════════════════"
echo " 2. Последние ошибки бота"
echo "════════════════════════════════════════════════════════════"
if [ -f logs/bot.error.log ]; then
    tail -n 40 logs/bot.error.log
else
    echo "(logs/bot.error.log нет — процесс не стартовал ни разу)"
fi

echo
echo "── строки ERROR/CRITICAL из обычного лога ──────────────────"
if [ -f logs/bot.out.log ]; then
    grep -E 'ERROR|CRITICAL' logs/bot.out.log | tail -n 20
    echo
    echo "── последние строки лога (что бот делал перед тишиной) ─────"
    tail -n 15 logs/bot.out.log
else
    echo "(logs/bot.out.log нет)"
fi

echo
echo "════════════════════════════════════════════════════════════"
echo " 3. Что говорит Telegram"
echo "════════════════════════════════════════════════════════════"
"$PYTHON" -m scripts.doctor 2>&1 | tail -n 40

echo
echo "════════════════════════════════════════════════════════════"
echo " 4. Окружение: .env, Mongo, панель"
echo "════════════════════════════════════════════════════════════"
"$PYTHON" -m scripts.check_setup 2>&1 | grep -vE '^$' | tail -n 40

echo
echo "════════════════════════════════════════════════════════════"
echo " 5. Место и память"
echo "════════════════════════════════════════════════════════════"
df -h . | tail -n 1
free -m 2>/dev/null | sed -n '2p'
echo
echo "Версия в каталоге: $(grep -m1 "^VERSION" app/version.py 2>/dev/null)"
echo "Последний коммит:  $(git log -1 --format='%h %ad %s' --date=short 2>/dev/null)"

echo
echo "════════════════════════════════════════════════════════════"
echo " Что дальше"
echo "════════════════════════════════════════════════════════════"
cat <<'HINT'
Читать сверху вниз: первая ❌ — она и есть причина.

  restarts растёт          → процесс падает на старте, смотрите раздел 2
  статус stopped/errored   → pm2 restart rsvpn-bot --update-env
  «Стоит вебхук»           → снять его, иначе бот не получит ни одного
                              сообщения, сколько его ни перезапускай
  «Токен занят»            → где-то второй процесс: ps aux | grep main_bot
  Mongo не отвечает        → база, а не бот: systemctl status mongod
  места 0                  → логи: pm2 flush, затем перезапуск

Весь этот вывод можно отправить целиком — по нему причина видна.
HINT
