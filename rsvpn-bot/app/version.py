"""Версия сборки — чтобы «дошло ли обновление» можно было проверить взглядом.

Номер совпадает с номером архива и растёт при каждой выкладке. Печатается
в стартовой сводке бота и в `python -m scripts.check_setup`.

Зачем вообще: обновление на сервере может тихо не состояться — `git pull` в
каталоге без .git, распаковка не туда, перезапуск не того процесса. Снаружи
это выглядит как «поправили, а не работает», и время уходит на поиски бага,
которого нет. Один номер в логе отвечает на этот вопрос сразу.
"""

from __future__ import annotations

VERSION = '86'

# Что появилось в этой сборке — короткой строкой, чтобы по логу было понятно
# не только «другая», но и «та ли самая».
BUILD = 'ByPass кончается вместе с подпиской, /srvdel для тестов'


def version_line() -> str:
    return f'{VERSION} ({BUILD})'
