"""Именные ссылки приглашения: правила самой метки.

Вместо `ref_802421217` человеку выдаётся `ref_vlad`. Смысл не в красоте:
числовая ссылка ничего не говорит о том, откуда пришёл человек, а метку
можно выдать блогеру, вложить в конкретный пост и потом увидеть, сколько
она привела. Один и тот же человек может получить несколько меток — по
одной на канал, — и все они ведут на него.

Здесь только проверка имени, без базы: правила короткие, а ошибиться в них
дорого. Метка едет в ссылке `?start=ref_<метка>`, и Telegram разрешает в
аргументе start только латиницу, цифры, подчёркивание и дефис.
"""

from __future__ import annotations

import re

MIN_LENGTH = 2
MAX_LENGTH = 32

# Дефис не берём нарочно: аргумент /start разбирается по подчёркиванию, а
# лишний разделитель в метке — повод однажды получить «ref_a_b» и спорить,
# где кончается метка.
ALLOWED = re.compile(r'^[a-z0-9_]+$')

# Числовая метка запрещена: `ref_12345` уже означает «пригласил человек с
# таким id», и метка «12345» сделала бы ссылку двусмысленной.
ERRORS = {
    'short': f'Метка короче {MIN_LENGTH} символов.',
    'long': f'Метка длиннее {MAX_LENGTH} символов.',
    'chars': 'В метке только латинские буквы, цифры и подчёркивание.',
    'digits': 'Метка не может состоять из одних цифр — так выглядит обычная '
              'ссылка по id, и бот не различит их.',
}


def normalize(raw: str) -> str:
    """Привести метку к виду, в котором она хранится.

    Регистр не различаем: человек, которому дали `Vlad`, напишет в посте
    `vlad`, и ссылка обязана работать.
    """
    return (raw or '').strip().lstrip('@').lower()


def check(raw: str) -> str:
    """Пустая строка — метка годится. Иначе текст ошибки для человека."""
    tag = normalize(raw)
    if len(tag) < MIN_LENGTH:
        return ERRORS['short']
    if len(tag) > MAX_LENGTH:
        return ERRORS['long']
    if not ALLOWED.match(tag):
        return ERRORS['chars']
    if tag.isdigit():
        return ERRORS['digits']
    return ''


def link(bot_username: str, tag: str) -> str:
    return f'https://t.me/{bot_username}?start=ref_{tag}'
