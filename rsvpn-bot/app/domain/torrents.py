"""Торренты: что делать на N-м нарушении и как разбирать жалобу.

Правила без базы и без панели — их удобно читать и невозможно проверить
иначе, чем прочитав.

Лестница нарастающая, и каждая ступень должна быть понятна человеку
заранее: сначала предупреждение (IP ему уже закрыл фильтр на сервере),
потом заморозка подписки на полчаса нашими руками, и только потом
отключение навсегда. Смысл в том, чтобы отключение получал тот, кто
прочитал два предупреждения и продолжил, а не тот, кто один раз забыл
выключить клиент.
"""

from __future__ import annotations

WARN = 'warn'
FREEZE = 'freeze'
BLOCK = 'block'


def stage(count: int, *, freeze_at: int, block_at: int) -> str:
    """Что делаем на этом по счёту нарушении.

    Порог 0 выключает ступень: `block_at=0` — никогда не отключать,
    `freeze_at=0` — не замораживать. Ступень «выше» всегда старше: если
    пороги перепутали местами, отключение всё равно не случится раньше,
    чем человек получил заморозку.
    """
    if block_at and count >= max(block_at, freeze_at or 0):
        return BLOCK
    if freeze_at and count >= freeze_at:
        return FREEZE
    return WARN


# ── разбор жалобы «я ничего не качаю» ───────────────────────────────────────
#
# Проверить это автоматически нельзя: у нас нет и не должно быть содержимого
# трафика. Зато у нас есть то, чем настоящий торрент отличается от случайного
# срабатывания, — упорство. Клиент за сессию даёт десятки отчётов подряд и
# продолжает после предупреждения; ложное срабатывание выглядит как один-два
# отчёта и тишина.
#
# Поэтому здесь не вердикт, а подсказка тому, кто будет решать: числа,
# сведённые в одну фразу.

MANY_REPORTS = 10        # столько отчётов за одно окно — это раздача
STUBBORN = 3             # столько нарушений в разные окна — тем более

REAL = 'real'
UNCLEAR = 'unclear'
DOUBTFUL = 'doubtful'

HINTS = {
    REAL: 'Похоже на настоящую раздачу: столько отчётов подряд даёт только '
          'работающий торрент-клиент.',
    UNCLEAR: 'Однозначного ответа нет. Спросите, что было запущено: '
             'некоторые игровые лаунчеры и обновления раздают через тот же '
             'протокол.',
    DOUBTFUL: 'Похоже на случайное срабатывание: одиночный отчёт и тишина. '
              'Так выглядят лаунчеры, обновления через P2P и чужое '
              'устройство в той же сети.',
}


def verdict(stats: dict) -> tuple[str, str]:
    """(код, фраза для карточки жалобы). Решает всё равно человек."""
    reports = int((stats or {}).get('reports') or 0)
    count = int((stats or {}).get('count') or 0)
    nodes = len((stats or {}).get('nodes') or ())

    if reports >= MANY_REPORTS or count >= STUBBORN or nodes > 1:
        return REAL, HINTS[REAL]
    if reports <= 2 and count <= 1:
        return DOUBTFUL, HINTS[DOUBTFUL]
    return UNCLEAR, HINTS[UNCLEAR]
